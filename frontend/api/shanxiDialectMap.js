// 核心转换函数：普通话文本 → 陕西方言文本
export const convertToShanxiDialect = (mandarinText) => {
  if (!mandarinText || typeof mandarinText !== 'string') return ''

  let dialectText = mandarinText.trim()

  const { sentenceMap, phraseMap, wordMap } = shanxiDialectMap

  // 第一步：匹配完整短句（优先级最高，避免拆分）
  Object.keys(sentenceMap).forEach((sentence) => {
    if (dialectText.includes(sentence)) {
      dialectText = dialectText.replace(new RegExp(sentence, 'g'), sentenceMap[sentence])
    }
  })

  // 第二步：匹配常用短语
  Object.keys(phraseMap).forEach((phrase) => {
    if (dialectText.includes(phrase)) {
      dialectText = dialectText.replace(new RegExp(phrase, 'g'), phraseMap[phrase])
    }
  })

  // 第三步：匹配基础词汇（逐词替换）
  Object.keys(wordMap).forEach((word) => {
    if (dialectText.includes(word)) {
      dialectText = dialectText.replace(new RegExp(word, 'g'), wordMap[word])
    }
  })

  // 陕西口语化收尾调整（贴合本地习惯，可按需细化）
  dialectText = dialectText
    .replace(/哈/g, '哈')
    .replace(/哩$/g, '哩')
    .replace(/咧$/g, '咧')
    .replace(/么$/g, '么')

  return dialectText
}

